export const AIM_STATES = ['ground', 'plane', 'freefall', 'chute']
export const MOVE_STATES = [
  'idle',
  'run',
  'sprint',
  'tactical',
  'slide',
  'crouch',
  'jump',
  'mantle',
  'climb',
  'plane',
  'freefall',
  'chute',
  'downed',
]
export function readActor(a) {
  const [
    id,
    name,
    team,
    x,
    y,
    z,
    yaw,
    pitch,
    height,
    air,
    stance,
    health,
    armor,
    kills,
    deaths,
    alive,
    weapon,
    vx,
    vz,
    shotAt,
    bot,
    assists,
    downed,
    operator,
    captures,
    revives,
    objective,
    reviveProgress,
    role,
    owner,
    confirms,
    denies,
    gunStage,
    streak,
    finish,
    sideFinish,
  ] = a
  return {
    id,
    name,
    team,
    x,
    y,
    z,
    yaw,
    pitch,
    height,
    air: AIM_STATES[air],
    stance: MOVE_STATES[stance],
    health,
    armor,
    kills,
    deaths,
    alive: !!alive,
    weapon,
    vx,
    vz,
    shotAt,
    bot: !!bot,
    assists,
    downed: !!downed,
    operator,
    captures,
    revives,
    objective,
    reviveProgress,
    role,
    owner: !!owner,
    confirms,
    denies,
    gunStage,
    streak,
    loadout: { finish, sideFinish },
  }
}
